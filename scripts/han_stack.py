#!/usr/bin/env python3
"""HAN stack manager for a single machine (development and the production pilot on this server).

    ~/.han-venvs/han/bin/python scripts/han_stack.py [--profile dev|prod] COMMAND
        build         build the frontend (production bundle)
        start         PostgreSQL -> migrations/seed -> model service -> backend -> frontend
        stop | status | logs [service]
        ensure        start anything that is not running, restart hung services; silent when healthy (used by cron)
        backup        database dump to <data>/backups (14 kept)
        install-cron  add the @reboot / every-minute `ensure` and the daily `backup` entries to the user crontab
        manage ...    account management, e.g.  manage add-users --project "TNI Translator Pilot" --role translator a@x.org b@x.org
                                                manage reset-password a@x.org      (generated passwords are shown once)

Profiles
    dev   data in ~/han-data       HAN_ENV=development, demo users, plain HTTP on localhost
    prod  data in ~/han-data-prod  HAN_ENV=production behind Apache at https://han.tniglobal.org and https://hanapi.tniglobal.org
Both bind to 127.0.0.1 only (frontend :3030, backend :8030, model service :9030) so they cannot run at the same time.
Secrets and first-run logins are generated into the data folder (mode 600), OUTSIDE the web root. Never commit them.

Not a high-availability setup: one machine, one database, one model process. The model is enabled with the model card's licence
recorded as evidence of a DEVELOPMENT check; that is not legal clearance (see README).
"""
from __future__ import annotations

import argparse
import os
import secrets
import shutil
import signal
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOME = Path.home()
VENV_HAN, VENV_INF = HOME / ".han-venvs" / "han" / "bin", HOME / ".han-venvs" / "inference" / "bin"
MODEL_DIR = HOME / "han-models" / ".hf"
PORTS = {"frontend": 3030, "backend": 8030, "inference": 9030, "assistant": 9031}
CHAT_MODEL = HOME / "han-models" / "chat" / "qwen2.5-1.5b-instruct-q4_k_m.gguf"
EMBED_MODEL = HOME / "han-models" / "embed" / "multilingual-e5-small"
MODEL_ID, MODEL_KEY = "google/madlad400-3b-mt", "madlad-400-3b-mt"
SERVICES = ("inference", "assistant", "backend", "frontend")
MARKER = {"inference": "server:app", "assistant": "assistant:app", "backend": "app.main:app", "frontend": "next"}  # substring of /proc/<pid>/cmdline
FAIL_LIMIT = {"inference": 20, "assistant": 10, "backend": 3, "frontend": 3}  # consecutive failed `ensure` runs (about minutes) before a restart
PATH = "/usr/local/bin:/usr/bin:/bin"

PROFILES = {
    "dev": dict(data=HOME / "han-data", env="development", url="http://127.0.0.1:3030", admin="admin@example.test", ops="ops@example.test"),
    "prod": dict(data=HOME / "han-data-prod", env="production", url="https://han.tniglobal.org", admin="han.admin@tniglobal.org",
                 ops="han.ops@tniglobal.org"),
}
PILOT_ACCOUNTS = 10  # generic pilot translator logins created on the first production start


class Stack:
    def __init__(self, profile: str):
        self.profile = profile
        self.cfg = PROFILES[profile]
        self.data: Path = self.cfg["data"]
        self.pg_dir, self.logs, self.run, self.backups = (self.data / "pg", self.data / "logs", self.data / "run", self.data / "backups")
        self.env_file, self.cred_file = self.data / "han.env", self.data / "credentials.txt"
        self.is_prod = profile == "prod"

    # ------------------------------------------------------------------ helpers
    def say(self, msg: str, quiet: bool = False) -> None:
        if not quiet:
            print(msg, flush=True)

    def ensure_dirs(self) -> None:
        for d in (self.data, self.logs, self.run, self.backups):
            d.mkdir(parents=True, exist_ok=True)
        self.data.chmod(0o700)

    def secrets_env(self) -> dict:
        self.ensure_dirs()
        if not self.env_file.exists():
            body = f"HAN_SECRET_KEY={secrets.token_urlsafe(48)}\nHAN_INFERENCE_TOKEN={secrets.token_urlsafe(32)}\n"
            self.env_file.write_text("# generated by scripts/han_stack.py; keep private\n" + body)
            self.env_file.chmod(0o600)
        return dict(l.split("=", 1) for l in self.env_file.read_text().splitlines() if l and not l.startswith("#") and "=" in l)

    def db_url(self) -> str:
        import pgserver

        self.pg_dir.mkdir(parents=True, exist_ok=True)
        server = pgserver.get_server(self.pg_dir, cleanup_mode=None)  # None: PostgreSQL keeps running after this script exits
        return server.get_uri().replace("postgresql://", "postgresql+psycopg://", 1)

    def backend_env(self, sec: dict, db_url: str) -> dict:
        env = {**os.environ, **sec, "PATH": PATH, "HAN_ENV": self.cfg["env"], "HAN_DATABASE_URL": db_url, "HAN_ENABLE_MOCK_PROVIDER": "0",
               "HAN_JOBS_BACKGROUND": "1", "HAN_JOBS_EAGER": "0", "HAN_MADLAD_URL": f"http://127.0.0.1:{PORTS['inference']}",
               "HAN_ASSISTANT_URL": f"http://127.0.0.1:{PORTS['assistant']}",
               "HAN_PROVIDER_TIMEOUT_S": "240" if self.is_prod else "180", "HAN_PROVIDER_RETRIES": "0", "HAN_LOG_LEVEL": "INFO",
               "PYTHONPATH": str(ROOT / "backend")}
        if self.is_prod:  # behind Apache's reverse proxy; the model processes 4,000 characters per request at most
            env.update(HAN_TRUST_PROXY="1", HAN_MAX_TEXT_CHARS="4000", HAN_RATE_LIMIT_AUTH_PER_MIN="30")
        return env

    # ------------------------------------------------------------------ processes
    def pid(self, name: str) -> int | None:
        try:
            pid = int((self.run / f"{name}.pid").read_text())
            cmd = Path(f"/proc/{pid}/cmdline").read_bytes().decode(errors="replace")
        except (OSError, ValueError):
            return None
        return pid if MARKER[name] in cmd else None

    def alive(self, name: str) -> bool:
        return self.pid(name) is not None

    def spawn(self, name: str, cmd: list, cwd: Path, env: dict, quiet: bool = False) -> None:
        if self.alive(name):
            self.say(f"  {name}: already running", quiet)
            return
        log = open(self.logs / f"{name}.log", "ab")
        p = subprocess.Popen(cmd, cwd=cwd, env=env, stdout=log, stderr=log, stdin=subprocess.DEVNULL, start_new_session=True)
        (self.run / f"{name}.pid").write_text(str(p.pid))
        self.say(f"  {name}: started (pid {p.pid})", quiet)

    def kill(self, name: str) -> None:
        pid = self.pid(name)
        if pid:
            try:
                os.killpg(os.getpgid(pid), signal.SIGTERM)
            except OSError:
                pass
        (self.run / f"{name}.pid").unlink(missing_ok=True)

    def commands(self, sec: dict, db_url: str) -> dict:
        inf_env = {**os.environ, "PATH": PATH, "HF_HOME": str(MODEL_DIR), "HF_HUB_OFFLINE": "1", "HAN_INFERENCE_TOKEN": sec["HAN_INFERENCE_TOKEN"],
                   "HAN_INFERENCE_MODEL_MADLAD": MODEL_ID, "HAN_INFERENCE_PRELOAD": "madlad"}
        asst_env = {**os.environ, "PATH": PATH, "HAN_INFERENCE_TOKEN": sec["HAN_INFERENCE_TOKEN"], "HAN_ASSISTANT_CHAT_MODEL": str(CHAT_MODEL),
                    "HAN_ASSISTANT_EMBED_MODEL": str(EMBED_MODEL), "HAN_ASSISTANT_THREADS": "10", "HAN_ASSISTANT_PRELOAD": "1"}
        return {
            "assistant": ([str(VENV_INF / "python"), "-m", "uvicorn", "assistant:app", "--host", "127.0.0.1", "--port", str(PORTS["assistant"])],
                          ROOT / "inference", asst_env),
            "inference": ([str(VENV_INF / "python"), "-m", "uvicorn", "server:app", "--host", "127.0.0.1", "--port", str(PORTS["inference"])],
                          ROOT / "inference", inf_env),
            "backend": ([str(VENV_HAN / "python"), "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1", "--port", str(PORTS["backend"]),
                         "--proxy-headers", "--forwarded-allow-ips", "127.0.0.1"], ROOT / "backend", self.backend_env(sec, db_url)),
            "frontend": ([str(ROOT / "frontend" / "node_modules" / ".bin" / "next"), "start", "-p", str(PORTS["frontend"]), "-H", "127.0.0.1"],
                         ROOT / "frontend", {**os.environ, "PATH": PATH, "NODE_ENV": "production", "NEXT_TELEMETRY_DISABLED": "1",
                                              "HAN_BACKEND_URL": f"http://127.0.0.1:{PORTS['backend']}"}),
        }

    @staticmethod
    def assistant_ready() -> bool:
        return CHAT_MODEL.exists() and EMBED_MODEL.is_dir()

    def healthy(self, name: str) -> bool:
        import httpx

        path = "/login" if name == "frontend" else "/healthz"
        try:
            return httpx.get(f"http://127.0.0.1:{PORTS[name]}{path}", timeout=5).status_code < 500
        except Exception:
            return False

    def wait_http(self, name: str, timeout: float) -> None:
        end = time.time() + timeout
        while time.time() < end:
            if self.healthy(name):
                self.say(f"  {name}: ready")
                return
            time.sleep(1)
        raise SystemExit(f"{name} did not become ready within {int(timeout)}s; see {self.logs}/{name}.log")

    # ------------------------------------------------------------------ bootstrap
    def run_py(self, args: list, env: dict, capture: bool = True) -> str:
        r = subprocess.run([str(VENV_HAN / "python"), *args], cwd=ROOT / "backend", env=env, check=True, capture_output=capture, text=True)
        return r.stdout or ""

    def bootstrap(self, sec: dict, db_url: str) -> None:
        """Migrations + reference data on every start (idempotent); one-time first-run accounts."""
        env = self.backend_env(sec, db_url)
        self.run_py(["-m", "alembic", "upgrade", "head"], env)
        if self.cred_file.exists():
            self.run_py(["-m", "app.seed"] + (["--pilot"] if self.is_prod else []), env)
            return
        admin_pw, ops_pw = secrets.token_urlsafe(14), secrets.token_urlsafe(14)
        seed_env = {**env, "HAN_BOOTSTRAP_TNI_ADMIN_EMAIL": self.cfg["admin"], "HAN_BOOTSTRAP_TNI_ADMIN_PASSWORD": admin_pw,
                    "HAN_BOOTSTRAP_TECH_ADMIN_EMAIL": self.cfg["ops"], "HAN_BOOTSTRAP_TECH_ADMIN_PASSWORD": ops_pw}
        lines = [f"HAN logins for the '{self.profile}' stack (generated on first start). Keep this file private (mode 600).",
                 f"URL: {self.cfg['url']}", "", "ADMINISTRATORS", f"  TNI administrator        {self.cfg['admin']:<36} {admin_pw}",
                 f"  Technical administrator  {self.cfg['ops']:<36} {ops_pw}"]
        if self.is_prod:
            self.run_py(["-m", "app.seed", "--pilot"], seed_env)
            pilot = [f"pilot{i:02d}@tniglobal.org" for i in range(1, PILOT_ACCOUNTS + 1)]
            out = self.run_py(["-m", "app.manage", "add-users", "--project", "TNI Translator Pilot", "--role", "translator", *pilot], env)
            rev = self.run_py(["-m", "app.manage", "add-users", "--project", "TNI Translator Pilot", "--role", "reviewer", "pilot.reviewer@tniglobal.org"], env)
            lines += ["", "PILOT TRANSLATORS (project: TNI Translator Pilot)"] + [f"  {l}" for l in out.strip().splitlines()]
            lines += ["", "PILOT REVIEWER (can see all pilot work)"] + [f"  {l}" for l in rev.strip().splitlines()]
        else:
            out = self.run_py(["-m", "app.seed", "--demo"], seed_env)
            lines += ["", "DEMO USERS"]
            for line in out.splitlines():
                if "generated password (shown once): " in line:
                    who, pw = line.split("  generated password (shown once): ")
                    lines.append(f"  {who.split(':', 1)[1].strip():<36} {pw.strip()}")
        self.cred_file.write_text("\n".join(lines) + "\n")
        self.cred_file.chmod(0o600)

    def enable_model(self, quiet: bool = False) -> None:
        """Enable the downloaded model through the protected admin API (idempotent)."""
        import httpx

        ops_pw = next(l.split()[-1] for l in self.cred_file.read_text().splitlines() if "Technical administrator" in l)
        c = httpx.Client(base_url=f"http://127.0.0.1:{PORTS['backend']}", timeout=60)
        r = c.post("/v1/auth/login", json={"email": self.cfg["ops"], "password": ops_pw})
        r.raise_for_status()
        # production cookies are `Secure`, so a plain-HTTP loopback client would not send them back: pass it explicitly
        h = {"X-CSRF-Token": r.json()["csrf_token"], "Cookie": f"han_session={r.cookies.get('han_session')}"}
        models = c.get("/v1/admin/models", headers=h)
        models.raise_for_status()
        if {m["key"]: m for m in models.json()}.get(MODEL_KEY, {}).get("enabled"):
            self.say(f"  model: {MODEL_KEY} already enabled", quiet)
            return
        c.patch(f"/v1/admin/models/{MODEL_KEY}", headers=h, json={
            "license": "Apache-2.0", "license_cleared": True, "deployment_status": "deployed", "enabled": True,
            "license_evidence": f"Model card {MODEL_ID} lists Apache-2.0 (checked {datetime.now():%Y-%m-%d}). NOT legal clearance: "
                                "TNI legal must confirm before use with client content."}).raise_for_status()
        self.say(f"  model: {MODEL_KEY} enabled (development licence evidence recorded)")

    # ------------------------------------------------------------------ commands
    def build(self) -> None:
        self.say("Building the frontend (production bundle)")
        fe = ROOT / "frontend"
        subprocess.run(["npm", "ci"], cwd=fe, check=True, env={**os.environ, "PATH": PATH})
        subprocess.run(["npm", "run", "build"], cwd=fe, check=True, env={**os.environ, "PATH": PATH, "NEXT_TELEMETRY_DISABLED": "1"})

    def start(self) -> None:
        sec = self.secrets_env()
        self.say(f"Starting HAN ({self.profile})")
        if not (MODEL_DIR / "hub").exists():
            raise SystemExit(f"model weights not found in {MODEL_DIR}; see README 'Running a real engine'")
        if not (ROOT / "frontend" / ".next" / "BUILD_ID").exists():
            raise SystemExit("frontend is not built: run `han_stack.py build` first")
        other = Stack("dev" if self.is_prod else "prod")
        if any(other.alive(n) for n in SERVICES):
            raise SystemExit(f"the {other.profile} stack is running on the same ports: stop it first (han_stack.py --profile {other.profile} stop)")
        self.say("  database: starting PostgreSQL (persistent)")
        db_url = self.db_url()
        self.bootstrap(sec, db_url)
        cmds = self.commands(sec, db_url)
        self.spawn("inference", *cmds["inference"])
        if self.assistant_ready():
            self.spawn("assistant", *cmds["assistant"])
        else:
            self.say("  assistant: model files not found; HAN will use its built-in rule-based replies (see docs/assistant.md)")
        self.spawn("backend", *cmds["backend"])
        self.wait_http("backend", 90)
        self.enable_model()
        self.spawn("frontend", *cmds["frontend"])
        self.wait_http("frontend", 90)
        self.say("  inference: loading the model (1-3 minutes); translations wait until it is ready")
        self.wait_http("inference", 600)
        if self.assistant_ready():
            self.wait_http("assistant", 300)
        self.say(f"\nHAN ({self.profile}) is running:  {self.cfg['url']}\nLogins:  cat {self.cred_file}\nStop:    han_stack.py --profile {self.profile} stop")

    def stop(self) -> None:
        for name in reversed(SERVICES):
            if self.alive(name):
                self.kill(name)
                self.say(f"  {name}: stopped")
            (self.run / f"{name}.pid").unlink(missing_ok=True)
        try:
            import pgserver

            pgserver.get_server(self.pg_dir, cleanup_mode="stop").cleanup()
            self.say("  database: stopped")
        except Exception as e:  # noqa: BLE001
            self.say(f"  database: {e}")

    def status(self) -> None:
        self.say(f"HAN stack '{self.profile}'  ->  {self.cfg['url']}")
        for name in SERVICES:
            self.say(f"  {name:<10} {'running' if self.alive(name) else 'stopped':<8} port {PORTS[name]}  {'healthy' if self.healthy(name) else 'not responding'}")

    def ensure(self) -> None:
        """Cron entry point: restore anything that died or hung. Prints only when it acts."""
        self.ensure_dirs()
        sec = self.secrets_env()
        if not self.cred_file.exists():
            return  # never started: refuse to bootstrap silently from cron
        db_url = self.db_url()
        cmds = self.commands(sec, db_url)
        for name in SERVICES:
            if name == "assistant" and not self.assistant_ready():
                continue
            fails = self.run / f"{name}.fails"
            if self.alive(name) and not self.healthy(name):
                n = (int(fails.read_text()) if fails.exists() else 0) + 1
                fails.write_text(str(n))
                if n >= FAIL_LIMIT[name]:
                    self.say(f"{datetime.now():%F %T} {name}: unresponsive for {n} checks, restarting")
                    self.kill(name)
                    fails.unlink(missing_ok=True)
            else:
                fails.unlink(missing_ok=True)
            if not self.alive(name):
                self.say(f"{datetime.now():%F %T} {name}: not running, starting")
                self.spawn(name, *cmds[name])
        for name in SERVICES:  # rotate by copy-and-truncate (the services keep appending to the same file)
            log = self.logs / f"{name}.log"
            if log.exists() and log.stat().st_size > 50_000_000:
                shutil.copyfile(log, self.logs / f"{name}.log.1")
                open(log, "w").close()

    def backup(self) -> None:
        import pgserver

        self.ensure_dirs()
        pg_dump = Path(pgserver.__file__).parent / "pginstall" / "bin" / "pg_dump"
        out = self.backups / f"han-{datetime.now():%Y%m%d-%H%M%S}.dump"
        subprocess.run([str(pg_dump), "-h", str(self.pg_dir), "-U", "postgres", "-d", "postgres", "-Fc", "-f", str(out)], check=True)
        out.chmod(0o600)
        for old in sorted(self.backups.glob("han-*.dump"))[:-14]:
            old.unlink()
        self.say(f"backup written: {out} ({out.stat().st_size // 1024} KiB)")
        try:  # retention: permanently remove conversations deleted longer ago than the retention period
            self.manage(["purge-conversations"])
        except subprocess.CalledProcessError:
            self.say("conversation purge failed (will retry tomorrow)")

    def install_cron(self) -> None:
        script = f"{VENV_HAN / 'python'} -W ignore {Path(__file__).resolve()} --profile {self.profile}"
        lock = self.run / "ensure.lock"
        log = self.logs / "cron.log"
        wanted = [f"@reboot PATH={PATH} flock -n {lock} {script} ensure >> {log} 2>&1",
                  f"* * * * * PATH={PATH} flock -n {lock} {script} ensure >> {log} 2>&1",
                  f"*/5 * * * * PATH={PATH} {script} reminders >> {log} 2>&1",
                  f"15 3 * * * PATH={PATH} {script} backup >> {log} 2>&1"]
        cur = subprocess.run(["crontab", "-l"], capture_output=True, text=True)
        existing = [l for l in (cur.stdout.splitlines() if cur.returncode == 0 else []) if l.strip()]
        keep = [l for l in existing if f"--profile {self.profile}" not in l or "han_stack.py" not in l]
        new = keep + wanted
        subprocess.run(["crontab", "-"], input="\n".join(new) + "\n", text=True, check=True)
        self.say(f"cron installed for profile '{self.profile}' ({len(wanted)} entries; {len(keep)} existing entries preserved)")

    def manage(self, args: list) -> None:
        """Run `python -m app.manage ...` against this profile's database."""
        if not args:
            raise SystemExit("usage: han_stack.py --profile prod manage add-users|reset-password ...")
        env = self.backend_env(self.secrets_env(), self.db_url())
        subprocess.run([str(VENV_HAN / "python"), "-W", "ignore", "-m", "app.manage", *args], cwd=ROOT / "backend", env=env, check=True)

    def reminders(self) -> None:
        """Send due incomplete-registration reminder emails."""
        env = self.backend_env(self.secrets_env(), self.db_url())
        subprocess.run([str(VENV_HAN / "python"), "-W", "ignore", "-m", "app.send_registration_reminders"], cwd=ROOT / "backend", env=env, check=True)

    def show_logs(self, service: str | None) -> None:
        for name in ([service] if service else SERVICES):
            f = self.logs / f"{name}.log"
            self.say(f"--- {name} ---")
            if f.exists():
                self.say("\n".join(f.read_text(errors="replace").splitlines()[-15:]))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", choices=sorted(PROFILES), default="dev")
    ap.add_argument("command", choices=["build", "start", "stop", "status", "logs", "ensure", "backup", "install-cron", "manage", "reminders"])
    ap.add_argument("args", nargs=argparse.REMAINDER)
    a = ap.parse_args()
    s = Stack(a.profile)
    if a.command == "logs" and a.args and a.args[0] not in SERVICES:
        raise SystemExit(f"logs: service must be one of {SERVICES}")
    {"build": s.build, "start": s.start, "stop": s.stop, "status": s.status, "ensure": s.ensure, "backup": s.backup,
     "install-cron": s.install_cron, "reminders": s.reminders, "manage": lambda: s.manage(a.args),
     "logs": lambda: s.show_logs(a.args[0] if a.args else None)}[a.command]()


if __name__ == "__main__":
    main()
